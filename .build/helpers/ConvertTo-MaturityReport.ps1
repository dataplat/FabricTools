function ConvertTo-MaturityReport
{
    <#
    .SYNOPSIS
        Renders the output of Get-CommandMaturity as the Markdown report docs/MATURITY.md.

    .DESCRIPTION
        The report has a summary of how many cmdlets sit at each level, followed by one table
        per item type listing each cmdlet, its level and what it is missing for the next level.
        It contains no date, so regenerating it changes the file only when a level changes.

    .PARAMETER Result
        Objects returned by Get-CommandMaturity.

    .EXAMPLE
        Get-CommandMaturity @params | ConvertTo-MaturityReport | Set-Content ./docs/MATURITY.md
    #>
    [CmdletBinding()]
    [OutputType([System.String])]
    param
    (
        [Parameter(Mandatory = $true, ValueFromPipeline = $true)]
        [AllowEmptyCollection()]
        [object[]]
        $Result
    )

    begin
    {
        $all = [System.Collections.Generic.List[object]]::new()
    }

    process
    {
        foreach ($item in $Result) { $all.Add($item) }
    }

    end
    {
        $levelNames = [ordered]@{
            0 = 'Experimental'
            1 = 'Prototype'
            2 = 'Standardized'
            3 = 'Unit Tested'
            4 = 'Integration Tested'
            5 = 'Production Ready'
        }

        $lines = [System.Collections.Generic.List[string]]::new()
        $lines.Add('# Cmdlet Maturity Report')
        $lines.Add('')
        $lines.Add('<!-- Generated by ./build.ps1 -Tasks generate_maturity_report. Do not edit by hand. -->')
        $lines.Add('')
        $lines.Add('Maturity level of every public cmdlet, computed from the source by `.build/helpers/Get-CommandMaturity.ps1`.')
        $lines.Add('The levels and their criteria are defined in [maturity-model.md](maturity-model.md).')
        $lines.Add('')
        $lines.Add('## Summary')
        $lines.Add('')
        $lines.Add('| Level | Name | Cmdlets |')
        $lines.Add('| ----: | ---- | ------: |')
        foreach ($level in $levelNames.Keys)
        {
            $count = @($all | Where-Object Level -eq $level).Count
            $lines.Add("| $level | $($levelNames[$level]) | $count |")
        }
        $lines.Add("| | **Total** | **$($all.Count)** |")

        foreach ($group in $all | Group-Object -Property ItemType | Sort-Object -Property Name)
        {
            $lines.Add('')
            $lines.Add("## $($group.Name)")
            $lines.Add('')
            $lines.Add('| Command | Level | Missing for next level | Note |')
            $lines.Add('| ------- | ----: | ---------------------- | ---- |')
            foreach ($item in $group.Group | Sort-Object -Property Name, Path)
            {
                $missing = (@($item.MissingForNext) | Where-Object { $_ } | ForEach-Object {
                        if ($_ -match '^\w+$') { "``$_``" } else { $_ }
                    }) -join ', '
                $note = if ($item.Note) { $item.Note -replace '\|', '\|' } else { '' }
                $lines.Add("| $($item.Name) | $($item.Level) $($item.LevelName) | $missing | $note |")
            }
        }

        $lines
    }
}
